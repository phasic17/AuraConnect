private func hash(_ i: Int, _ s: Double) -> Double {
    let v = sin(Double(i) * s) * 43758.5453
    return v - v.rounded(.down)
}

struct AuraBackground: View {
    var energy: Double = 0.6
    @State private var t: Double = 0.0
    private let timer = Timer.publish(every: 1.0 / 30.0, on: .main, in: .common).autoconnect()
    var body: some View {
        let e = max(0.0, min(2.0, energy))
        return Canvas { ctx, size in drawScene(ctx, size, t, e) }
            .ignoresSafeArea()
            .onReceive(timer) { _ in t += 1.0 / 30.0 }
    }
}

private func drawScene(_ ctx: GraphicsContext, _ size: CGSize, _ t: Double, _ e: Double) {
    let W = Double(size.width), H = Double(size.height)
    ctx.fill(Path(CGRect(origin: .zero, size: size)), with: .color(Color(red: 0.010, green: 0.009, blue: 0.016)))
    drawStars(ctx, size, t)
    drawWorldMap(ctx, size, t, e)
    drawComet(ctx, size, t)
    let vig = GraphicsContext.Shading.radialGradient(
        Gradient(colors: [.clear, .black.opacity(0.26)]),
        center: CGPoint(x: W / 2, y: H / 2), startRadius: min(W, H) * 0.5, endRadius: max(W, H) * 0.98)
    ctx.fill(Path(CGRect(origin: .zero, size: size)), with: vig)
}

private func drawWorldMap(_ ctx: GraphicsContext, _ size: CGSize, _ t: Double, _ e: Double) {
    let W = Double(size.width), H = Double(size.height)
    let cols = Double(WorldMap.cols), rows = Double(WorldMap.nrows)
    let mapH = H * 0.84, offY = H * 0.08
    let stepX = W / cols, stepY = mapH / rows
    let period = 44.0
    let sweepX = (t / period - (t / period).rounded(.down)) * W
    let g = WorldMap.grid
    for r in 0..<WorldMap.nrows {
        let rowArr = g[r]
        for c in 0..<WorldMap.cols {
            if rowArr[c] != "1" { continue }
            let x = Double(c) * stepX + stepX / 2
            let y = offY + Double(r) * stepY + stepY / 2
            let baseHue = 0.03 + 0.55 * (Double(c) / cols)
            var d = abs(x - sweepX); if d > W / 2 { d = W - d }
            let near = max(0, 1 - d / (W * 0.13))
            let hue = baseHue + (0.085 - baseHue) * (near * 0.92)   // amber wash under the sweep
            let bright = 0.52 + 0.46 * near
            let sat = 0.74 + 0.24 * near
            let sz = 2.7 + 2.3 * near
            ctx.fill(Path(ellipseIn: CGRect(x: x - sz / 2, y: y - sz / 2, width: sz, height: sz)),
                     with: .color(Color(hue: hue, saturation: sat, brightness: bright, opacity: 0.64 + 0.36 * near)))
        }
    }
    let bar = GraphicsContext.Shading.linearGradient(
        Gradient(colors: [.clear, Color(red: 1, green: 0.69, blue: 0.28).opacity(0.17), .clear]),
        startPoint: CGPoint(x: sweepX - 75, y: 0), endPoint: CGPoint(x: sweepX + 75, y: 0))
    ctx.fill(Path(CGRect(x: sweepX - 75, y: offY, width: 150, height: mapH)), with: bar)
    let cities: [(Double, Double)] = [(40.7, -74), (51.5, -0.1), (35.7, 139.7), (-33.9, 151.2), (37.8, -122.4), (25.2, 55.3), (-23.5, -46.6), (1.3, 103.8)]
    for (i, ct) in cities.enumerated() {
        let x = (ct.1 + 180) / 360 * W
        let y = offY + (90 - ct.0) / 180 * mapH
        let ph = 0.5 + 0.5 * sin(t * 1.4 + Double(i) * 1.1)
        let s = 2.5 + 3.0 * ph
        ctx.fill(Path(ellipseIn: CGRect(x: x - s, y: y - s, width: s * 2, height: s * 2)), with: .color(BG_HOT.opacity(0.28 + 0.42 * ph)))
        ctx.fill(Path(ellipseIn: CGRect(x: x - 1.5, y: y - 1.5, width: 3, height: 3)), with: .color(.white.opacity(0.9)))
    }
}

private func drawStars(_ ctx: GraphicsContext, _ size: CGSize, _ t: Double) {
    let W = Double(size.width), H = Double(size.height)
    for i in 0..<90 {
        let x = hash(i, 12.9898) * W
        let y = hash(i, 78.233) * H
        let twin = 0.5 + 0.5 * sin(t * (0.4 + hash(i, 1.7) * 1.4) + Double(i))
        let op = (0.06 + 0.16 * hash(i, 3.17)) * (0.45 + 0.55 * twin)
        let s = 0.6 + 1.1 * hash(i, 5.1)
        ctx.fill(Path(ellipseIn: CGRect(x: x - s / 2, y: y - s / 2, width: s, height: s)), with: .color(.white.opacity(op)))
    }
}

private func drawComet(_ ctx: GraphicsContext, _ size: CGSize, _ t: Double) {
    let W = Double(size.width), H = Double(size.height)
    let period = 11.0
    let cyc = (t / period).rounded(.down)
    let local = t - cyc * period
    let dur = 1.6
    if local >= dur { return }
    let ci = Int(cyc)
    let p = local / dur
    let start = CGPoint(x: (0.08 + 0.8 * hash(ci, 24.3)) * W, y: (0.04 + 0.2 * hash(ci, 51.7)) * H)
    let ang = Double.pi * 0.16 + hash(ci, 9.1) * 0.34
    let dist = max(W, H) * 0.6
    let fade = sin(p * Double.pi)
    for k in 0..<16 {
        let tpp = max(p - Double(k) / 16 * 0.12, 0)
        let tx = start.x + CGFloat(cos(ang) * dist * tpp)
        let ty = start.y + CGFloat(sin(ang) * dist * tpp)
        let op = fade * (1 - Double(k) / 16) * 0.5
        let s = 2.0 * (1 - Double(k) / 16) + 0.4
        ctx.fill(Path(ellipseIn: CGRect(x: tx - s / 2, y: ty - s / 2, width: s, height: s)), with: .color(BG_HOT.opacity(op)))
    }
    let hx = start.x + CGFloat(cos(ang) * dist * p)
    let hy = start.y + CGFloat(sin(ang) * dist * p)
    ctx.fill(Path(ellipseIn: CGRect(x: hx - 2.2, y: hy - 2.2, width: 4.4, height: 4.4)), with: .color(.white.opacity(fade * 0.9)))
}
